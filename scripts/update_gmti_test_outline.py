def set_paragraph(paragraph, text: str) -> None:
    paragraph.clear()
    paragraph.add_run(text)


def resize_table(table, rows: int) -> None:
    while len(table.rows) < rows:
        table.add_row()
    while len(table.rows) > rows:
        table._tbl.remove(table.rows[-1]._tr)


def fill_table(table, values: list[list[str]]) -> None:
    resize_table(table, len(values))
    for r, row in enumerate(values):
        if len(row) != len(table.columns):
            raise ValueError(f"table row {r}: expected {len(table.columns)} cells, got {len(row)}")
        for c, value in enumerate(row):
            cell = table.cell(r, c)
            cell.text = value
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            for paragraph in cell.paragraphs:
                paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER


